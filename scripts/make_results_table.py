"""
scripts/make_results_table.py
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Reads outputs/metrics/*.json and:

  1. Fills the <!-- RESULTS:START --> … <!-- RESULTS:END --> block in README.md
     in-place with the current primary results (lesion split, seed 42).
  2. Prints the same table to stdout.
  3. Prints image-level and lesion-level imbalance ratios if the metadata CSV
     is present (for the GitHub "About" text).

Missing models show "—" in the table; no numbers are invented.

Usage (from repo root):
    python scripts/make_results_table.py

To also read the metadata CSV (for imbalance ratios), set the DATA_DIR env var:
    DATA_DIR=/path/to/ham10000/data python scripts/make_results_table.py
"""

import json
import os
import re
import sys
import glob

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
REPO_ROOT   = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
METRICS_DIR = os.path.join(REPO_ROOT, "outputs", "metrics")
README_PATH = os.path.join(REPO_ROOT, "README.md")

# Primary models in display order  (model_name, split_mode, seed, label)
PRIMARY = [
    ("baseline_cnn",    "lesion", 42, "Baseline CNN"),
    ("resnet18",        "lesion", 42, "ResNet18"),
    ("efficientnet_b0", "lesion", 42, "EfficientNet-B0"),
]

SENTINEL_START = "<!-- RESULTS:START -->"
SENTINEL_END   = "<!-- RESULTS:END -->"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_metrics(model_name: str, split_mode: str, seed: int):
    """Return the parsed JSON dict or None if the file is missing."""
    filename = f"{model_name}_{split_mode}_seed{seed}.json"
    path = os.path.join(METRICS_DIR, filename)
    if not os.path.exists(path):
        print(f"  (missing) {filename}", file=sys.stderr)
        return None
    with open(path) as f:
        return json.load(f)


def _r(data, key, fmt):
    """Format a metric or return '—' if data is missing."""
    if data is None:
        return "—"
    v = data
    for k in key.split("."):
        if isinstance(v, dict):
            v = v.get(k)
        else:
            v = None
        if v is None:
            return "—"
    try:
        return format(float(v), fmt)
    except (TypeError, ValueError):
        return "—"


def _recall(data, cls):
    if data is None:
        return "—"
    v = data.get("malignant_recall", {}).get(cls)
    if v is None:
        return "—"
    s = f"{v:.4f}"
    if float(v) < 0.5:
        s += " ⚠️"
    return s


def build_table(rows):
    """Return a Markdown table string from a list of row dicts."""
    header = ("| Model | Split | Accuracy | Macro F1 | Recall — mel "
              "| Recall — bcc | Recall — akiec |")
    sep    = ("|-------|-------|:--------:|:--------:|:------------:"
              "|:------------:|:--------------:|")
    lines  = [header, sep]
    for r in rows:
        lines.append(
            f"| {r['model']} | {r['split']} | {r['acc']} | {r['f1']} "
            f"| {r['mel']} | {r['bcc']} | {r['akiec']} |"
        )
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    print("make_results_table.py", file=sys.stderr)
    print(f"  metrics dir : {METRICS_DIR}", file=sys.stderr)
    print(f"  README      : {README_PATH}", file=sys.stderr)
    print("", file=sys.stderr)

    # --- build table rows ---
    rows = []
    for model_name, split_mode, seed, label in PRIMARY:
        data = load_metrics(model_name, split_mode, seed)
        rows.append({
            "model"  : label,
            "split"  : split_mode,
            "acc"    : _r(data, "accuracy",  ".2%"),
            "f1"     : _r(data, "macro_f1",  ".4f"),
            "mel"    : _recall(data, "mel"),
            "bcc"    : _recall(data, "bcc"),
            "akiec"  : _recall(data, "akiec"),
        })

    table = build_table(rows)

    # --- print to stdout ---
    print(table)
    print()
    note = ("_Table generated by `scripts/make_results_table.py` from "
            "`outputs/metrics/*.json`. Run the Colab notebooks first._")
    print(note)

    # --- update README.md in-place ---
    if not os.path.exists(README_PATH):
        print(f"\nREADME not found at {README_PATH} — skipping in-place update.",
              file=sys.stderr)
        return

    with open(README_PATH, encoding="utf-8") as f:
        content = f.read()

    new_block = (f"{SENTINEL_START}\n{table}\n"
                 f"\n{note}\n{SENTINEL_END}")

    pattern = re.compile(
        re.escape(SENTINEL_START) + r".*?" + re.escape(SENTINEL_END),
        re.DOTALL,
    )

    if not pattern.search(content):
        print(
            "\n⚠️  RESULTS sentinels not found in README.md — no in-place update.",
            file=sys.stderr,
        )
        print("   Add <!-- RESULTS:START --> and <!-- RESULTS:END --> markers.",
              file=sys.stderr)
        return

    new_content = pattern.sub(new_block, content)
    with open(README_PATH, "w", encoding="utf-8") as f:
        f.write(new_content)
    print(f"\nREADME.md updated in-place.", file=sys.stderr)

    # --- imbalance ratio from metadata CSV (optional) ---
    data_dir = os.environ.get("DATA_DIR") or os.path.join(REPO_ROOT, "data")
    csv_path = os.path.join(data_dir, "HAM10000_metadata.csv")
    if os.path.exists(csv_path):
        try:
            import pandas as pd
            df = pd.read_csv(csv_path)
            img_counts  = df["dx"].value_counts()
            img_ratio   = img_counts.max() / img_counts.min()
            lesion_df   = df.drop_duplicates(subset="lesion_id")
            les_counts  = lesion_df["dx"].value_counts()
            les_ratio   = les_counts.max() / les_counts.min()
            majority_cls  = img_counts.idxmax()
            minority_cls  = img_counts.idxmin()
            print(f"\nImbalance ratios (from {csv_path}):", file=sys.stderr)
            print(f"  Image-level  : {majority_cls}/{minority_cls} = "
                  f"{img_counts[majority_cls]}/{img_counts[minority_cls]} ≈ {img_ratio:.1f}:1",
                  file=sys.stderr)
            print(f"  Lesion-level : {majority_cls}/{minority_cls} = "
                  f"{les_counts[majority_cls]}/{les_counts[minority_cls]} ≈ {les_ratio:.1f}:1",
                  file=sys.stderr)
            print(f"\nGitHub About text suggestion:", file=sys.stderr)
            print(f"  'HAM10000 dermoscopy classifier — {len(img_counts)} classes, "
                  f"{len(df):,} images, {len(lesion_df):,} unique lesions, "
                  f"class imbalance {img_ratio:.0f}:1 (image) / {les_ratio:.0f}:1 (lesion)'",
                  file=sys.stderr)
        except Exception as e:
            print(f"\nCould not compute ratios from metadata: {e}", file=sys.stderr)
    else:
        print(f"\nMetadata CSV not found at {csv_path}.", file=sys.stderr)
        print("  Set DATA_DIR env var or run on Colab to compute exact imbalance ratios.",
              file=sys.stderr)


if __name__ == "__main__":
    main()
